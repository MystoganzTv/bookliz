#!/usr/bin/env node
/**
 * Builds src/ebook/epubReaderHtml.generated.ts: the page the EPUB reader
 * WebView loads, with JSZip and epub.js inlined so reading works offline and
 * never fetches code from a CDN.
 *
 * Run after installing or updating `epubjs` / `jszip`:
 *   node scripts/build-epub-reader.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const jszip = readFileSync(require.resolve("jszip/dist/jszip.min.js"), "utf8");
const epub = readFileSync(require.resolve("epubjs/dist/epub.min.js"), "utf8");
const app = readFileSync(join(here, "epub-reader-app.js"), "utf8");

const html = `<!doctype html>
<html><head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>html,body{margin:0;padding:0;height:100%;overflow:hidden;background:var(--bg,#fff)}#viewer{position:absolute;inset:0}</style>
<script>${jszip}</script>
<script>${epub}</script>
</head><body><div id="viewer"></div>
<script>${app}</script>
</body></html>`;

const out = join(here, "..", "src", "ebook", "epubReaderHtml.generated.ts");
writeFileSync(
  out,
  `/* eslint-disable */\n// GENERATED by scripts/build-epub-reader.mjs — do not edit by hand.\nexport const EPUB_READER_HTML: string = ${JSON.stringify(html)};\n`
);
console.log(`wrote ${out} (${Math.round(html.length / 1024)} KB)`);
